#!/usr/bin/env python3
"""Launch and control OpenMW for UI automation.

Each running game uses its own profile folder under .automation/profiles/<name>/ in the
repository. The profile holds the game's config, settings, log, saves and screenshots, so a
run never reads or writes the user's own OpenMW config folder. The profile's openmw.cfg is
built from the user's openmw.cfg, which tells the game where the Morrowind data files are.

Run "omw.py <command> --help" for the options of each command.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
AUTOMATION_DIR = REPO_ROOT / ".automation"
PROFILES_DIR = AUTOMATION_DIR / "profiles"

# Window sizes for the target devices. See ui-rework/plan.md.
RESOLUTIONS = {
    "deck": (1280, 800),
    "tv1080": (1920, 1080),
    "tv4k": (3840, 2160),
}

# openmw.cfg keys that the profile sets itself, so they are not copied from the user's file.
PROFILE_OWNED_CFG_KEYS = {"config", "user-data", "data-local", "resources", "replace", "no-sound"}


class HarnessError(Exception):
    pass


def default_build_dir():
    env = os.environ.get("OMW_BUILD_DIR")
    if env:
        return Path(env)
    return REPO_ROOT / "MSVC2022_64" / "RelWithDebInfo"


def default_user_cfg():
    env = os.environ.get("OMW_USER_CFG")
    if env:
        return Path(env)
    if sys.platform == "win32":
        return Path.home() / "Documents" / "My Games" / "OpenMW" / "openmw.cfg"
    return Path.home() / ".config" / "openmw" / "openmw.cfg"


def openmw_binary(build_dir):
    name = "openmw.exe" if sys.platform == "win32" else "openmw"
    path = build_dir / name
    if not path.is_file():
        raise HarnessError(f"{path} does not exist. Build the openmw target first.")
    return path


class Profile:
    def __init__(self, name):
        self.name = name
        self.root = PROFILES_DIR / name
        self.config_dir = self.root / "config"
        self.data_dir = self.root / "data"
        self.run_file = self.root / "run.json"
        self.stdout_file = self.root / "stdout.log"

    @property
    def log_file(self):
        return self.config_dir / "openmw.log"

    def read_run(self):
        if not self.run_file.is_file():
            return None
        return json.loads(self.run_file.read_text(encoding="utf-8"))

    def write_run(self, info):
        self.run_file.write_text(json.dumps(info, indent=2), encoding="utf-8")


def process_alive(pid):
    if sys.platform == "win32":
        result = subprocess.run(
            ["tasklist", "/FI", f"PID eq {pid}", "/NH", "/FO", "CSV"],
            capture_output=True,
            text=True,
        )
        return f'"{pid}"' in result.stdout
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    return True


def kill_process(pid):
    if sys.platform == "win32":
        subprocess.run(["taskkill", "/PID", str(pid), "/F"], capture_output=True)
    else:
        os.kill(pid, 9)


def write_openmw_cfg(profile, user_cfg):
    if not user_cfg.is_file():
        raise HarnessError(
            f"{user_cfg} does not exist. Set OMW_USER_CFG to an openmw.cfg that lists the Morrowind data files."
        )
    lines = [
        "# Generated by ui-rework/tools/omw.py. Do not edit; it is rewritten on every launch.",
        f"# Copied from {user_cfg}, minus the keys the harness sets itself.",
    ]
    for line in user_cfg.read_text(encoding="utf-8-sig").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        key = stripped.split("=", 1)[0].strip()
        if key in PROFILE_OWNED_CFG_KEYS:
            continue
        lines.append(stripped)
    (profile.config_dir / "openmw.cfg").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_settings_cfg(profile, args):
    width, height = RESOLUTIONS[args.resolution]
    sections = {
        "Video": {
            "resolution x": width,
            "resolution y": height,
            # 2 is windowed mode.
            "window mode": 2,
            "window border": "true",
            "screen": args.screen,
            "minimize on focus loss": "false",
            "framerate limit": 60,
            "vsync mode": 0,
        },
        "GUI": {
            "scaling factor": args.scale,
        },
        "General": {
            "screenshot format": "png",
            "notify on saved screenshot": "false",
        },
    }
    for setting in args.set or []:
        try:
            name, value = setting.split("=", 1)
            section, key = name.split(".", 1)
        except ValueError:
            raise HarnessError(f"--set expects Section.key=value, got {setting!r}")
        sections.setdefault(section.strip(), {})[key.strip()] = value.strip()

    lines = ["# Generated by ui-rework/tools/omw.py. Do not edit; it is rewritten on every launch."]
    for section, values in sections.items():
        lines.append(f"[{section}]")
        for key, value in values.items():
            lines.append(f"{key} = {value}")
    (profile.config_dir / "settings.cfg").write_text("\n".join(lines) + "\n", encoding="utf-8")


def start_arguments(args):
    if args.save:
        save = Path(args.save)
        if not save.is_absolute():
            save = Path.cwd() / save
        if not save.is_file():
            raise HarnessError(f"Save file {save} does not exist.")
        return ["--load-savegame", str(save)]
    if args.new_game:
        # Starts a new game with character creation.
        return ["--skip-menu", "--new-game"]
    if args.start:
        # Starts a new game in the given cell, skipping character creation.
        return ["--skip-menu", "--start", args.start]
    if args.skip_chargen:
        return ["--skip-menu"]
    return []


def cmd_launch(args):
    profile = Profile(args.profile)
    run = profile.read_run()
    if run and process_alive(run["pid"]):
        raise HarnessError(f"Profile {profile.name} already has a running game (pid {run['pid']}). Quit it first.")

    build_dir = Path(args.build_dir) if args.build_dir else default_build_dir()
    binary = openmw_binary(build_dir)

    profile.config_dir.mkdir(parents=True, exist_ok=True)
    profile.data_dir.mkdir(parents=True, exist_ok=True)
    if args.fresh:
        for leftover in profile.config_dir.iterdir():
            if leftover.is_file():
                leftover.unlink()
    write_openmw_cfg(profile, Path(args.user_cfg) if args.user_cfg else default_user_cfg())
    write_settings_cfg(profile, args)

    command = [
        str(binary),
        # Only use the profile's config folder. Without this, the build's own openmw.cfg also
        # pulls in the user's config folder.
        "--replace=config",
        "--config",
        str(profile.config_dir),
        "--user-data",
        str(profile.data_dir),
        "--data-local",
        str(profile.data_dir / "data"),
        "--no-grab",
    ]
    if not args.sound:
        command.append("--no-sound")
    command += start_arguments(args)
    command += args.extra

    with open(profile.stdout_file, "w", encoding="utf-8") as stdout:
        creation_flags = 0
        if sys.platform == "win32":
            creation_flags = subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.DETACHED_PROCESS
        process = subprocess.Popen(
            command,
            cwd=build_dir,
            stdout=stdout,
            stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL,
            creationflags=creation_flags,
        )

    profile.write_run(
        {
            "pid": process.pid,
            "command": command,
            "resolution": args.resolution,
            "started": time.strftime("%Y-%m-%d %H:%M:%S"),
        }
    )
    print(f"Launched {binary.name} (pid {process.pid}) with profile {profile.name} at {args.resolution}.")
    print(f"Log: {profile.log_file}")

    if args.wait_for:
        wait_for_log(profile, process.pid, args.wait_for, args.timeout)
        print(f"Saw {args.wait_for!r} in the log.")


def wait_for_log(profile, pid, text, timeout):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if profile.log_file.is_file() and text in profile.log_file.read_text(encoding="utf-8", errors="replace"):
            return
        if not process_alive(pid):
            raise HarnessError(f"The game exited before {text!r} appeared in the log. See {profile.log_file}.")
        time.sleep(0.25)
    raise HarnessError(f"Timed out after {timeout} s waiting for {text!r} in the log.")


def cmd_quit(args):
    profile = Profile(args.profile)
    run = profile.read_run()
    if not run or not process_alive(run["pid"]):
        print(f"No game is running for profile {profile.name}.")
        return
    kill_process(run["pid"])
    deadline = time.monotonic() + args.timeout
    while process_alive(run["pid"]) and time.monotonic() < deadline:
        time.sleep(0.25)
    if process_alive(run["pid"]):
        raise HarnessError(f"pid {run['pid']} is still running.")
    print(f"Stopped pid {run['pid']}.")


def cmd_status(args):
    profiles = [Profile(args.profile)] if args.profile else [
        Profile(p.name) for p in sorted(PROFILES_DIR.iterdir()) if p.is_dir()
    ] if PROFILES_DIR.is_dir() else []
    if not profiles:
        print("No profiles.")
    for profile in profiles:
        run = profile.read_run()
        if run and process_alive(run["pid"]):
            print(f"{profile.name}: running, pid {run['pid']}, {run['resolution']}, started {run['started']}")
        else:
            print(f"{profile.name}: not running")


def cmd_log(args):
    profile = Profile(args.profile)
    if not profile.log_file.is_file():
        raise HarnessError(f"{profile.log_file} does not exist.")
    lines = profile.log_file.read_text(encoding="utf-8", errors="replace").splitlines()
    if args.errors:
        lines = [line for line in lines if "[E]" in line or "[W]" in line or "rror" in line]
    for line in lines[-args.lines :]:
        print(line)


def cmd_clean(args):
    profile = Profile(args.profile)
    run = profile.read_run()
    if run and process_alive(run["pid"]):
        raise HarnessError(f"Profile {profile.name} has a running game. Quit it first.")
    if profile.root.is_dir():
        shutil.rmtree(profile.root)
    print(f"Removed {profile.root}.")


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    def add_profile(p):
        p.add_argument("--profile", "-p", default=os.environ.get("OMW_PROFILE", "default"),
                       help="profile name; each running game needs its own (default: $OMW_PROFILE or 'default')")

    p = sub.add_parser("launch", help="start the game in an isolated profile")
    add_profile(p)
    p.add_argument("--resolution", "-r", choices=RESOLUTIONS, default="deck")
    p.add_argument("--scale", type=float, default=1.0, help="GUI scaling factor (default 1.0)")
    p.add_argument("--screen", type=int, default=int(os.environ.get("OMW_SCREEN", "1")),
                   help="SDL display index for the window (default: $OMW_SCREEN or 1)")
    p.add_argument("--set", action="append", metavar="Section.key=value", help="extra setting; repeatable")
    start = p.add_mutually_exclusive_group()
    start.add_argument("--save", help="load this save file")
    start.add_argument("--new-game", action="store_true", help="start a new game with character creation")
    start.add_argument("--skip-chargen", action="store_true", help="start a new game without character creation")
    start.add_argument("--start", metavar="CELL", help="start a new game in this cell, without character creation")
    p.add_argument("--sound", action="store_true", help="leave sound on")
    p.add_argument("--fresh", action="store_true", help="delete the profile's leftover config files first")
    p.add_argument("--wait-for", metavar="TEXT", help="wait until this text appears in openmw.log")
    p.add_argument("--timeout", type=float, default=120)
    p.add_argument("--build-dir", help="folder holding the openmw binary (default: $OMW_BUILD_DIR or the MSVC build)")
    p.add_argument("--user-cfg", help="openmw.cfg that lists the game data (default: $OMW_USER_CFG or the user's)")
    p.add_argument("extra", nargs="*", help="extra arguments passed to openmw after --")
    p.set_defaults(func=cmd_launch)

    p = sub.add_parser("quit", help="stop the game")
    add_profile(p)
    p.add_argument("--timeout", type=float, default=10)
    p.set_defaults(func=cmd_quit)

    p = sub.add_parser("status", help="show which profiles have a running game")
    p.add_argument("--profile", "-p")
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("log", help="print the end of the game's log")
    add_profile(p)
    p.add_argument("--lines", "-n", type=int, default=40)
    p.add_argument("--errors", action="store_true", help="only warnings and errors")
    p.set_defaults(func=cmd_log)

    p = sub.add_parser("clean", help="delete a profile folder")
    add_profile(p)
    p.set_defaults(func=cmd_clean)

    return parser


def main():
    args = build_parser().parse_args()
    try:
        args.func(args)
    except HarnessError as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
